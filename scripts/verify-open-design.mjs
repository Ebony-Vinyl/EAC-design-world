  assert.equal(await picker.locator('.library-card').count(), frameBefore.width <= 600 ? 4 : 8);
  const composerAfter = await page.locator('[data-composer-card]').boundingBox();
  const frameAfter = await page.locator('iframe[data-eac-frame="recommendations"]').boundingBox();
  assert.equal(composerBefore.y, composerAfter.y);
  assert.equal(frameBefore.height, frameAfter.height);
