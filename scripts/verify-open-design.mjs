  await page.getByRole('button', { name: '用它新建作品', exact: true }).click();
  await page.getByRole('textbox', { name: '作品名称', exact: true }).fill('真实设计体系验收');
  await page.getByRole('button', { name: '创建作品', exact: true }).click();
  await page.getByRole('textbox', { name: '文件内容', exact: true }).waitFor();
  const code = page.getByRole('textbox', { name: '文件内容', exact: true });
  assert.match(await code.inputValue(), /--accent/);
  await code.fill('<!doctype html><html><body style="background:#123b2f;color:white"><h1>LIVE DESIGN PREVIEW</h1></body></html>');
  const preview = page.frameLocator('iframe[title="index.html 预览"]');
  await preview.getByRole('heading', { name: 'LIVE DESIGN PREVIEW' }).waitFor();
  await page.getByRole('button', { name: '保存新版本', exact: true }).click();
  await page.getByText('已保存 index.html · v2', { exact: true }).waitFor();
  const state = await engine.handle('design_state');
  assert.equal(state.projects[0].artifacts[0].revision, 2);
  checks.push('Design system seeds real CSS; editing live preview and immutable version save work');
  await page.setViewportSize({ width: 600, height: 780 });
  await page.getByRole('tab', { name: '预览作品', exact: true }).click();
  await page.screenshot({ path: join(directory, 'editor-600px.png') });
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1);
  assert.equal(overflow, false);
  checks.push('600px embedded workspace has no horizontal document overflow');
  await page.goto(`${app.url}/?view=canvas`);
  await page.getByText('真实设计体系验收', { exact: false }).waitFor();
  await page.screenshot({ path: join(directory, 'canvas-600px.png') });
  checks.push('Canvas discovers persisted design artifact');
  assert.deepEqual(errors, []);
  const media = join(dataDir, 'timeline-source.mp4');
