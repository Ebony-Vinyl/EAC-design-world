  await page.goto(`${fixtureUrl}/tests/fixtures/composer.html?backend=${encodeURIComponent(app.url)}`);
  const originalComposer = await page.locator('[data-composer-card]').boundingBox();
  const originalInput = await page.getByRole('textbox', { name: '测试草稿' }).boundingBox();
  await page.getByRole('button', { name: '创作模式: 正常模式', exact: true }).click();
  await page.getByRole('menuitem', { name: '剪辑模式', exact: true }).click();
  await page.locator('[data-eac-intro-seat]:not([hidden]) .eac-intro').waitFor();
  const picker = page.frameLocator('iframe[data-eac-frame="recommendations"]');
  await picker.getByRole('button', { name: '选择逐帧手绘', exact: true }).waitFor();
  await page.waitForTimeout(250);
  const composerBefore = await page.locator('[data-composer-card]').boundingBox();
  assert.ok(composerBefore.y >= 0 && composerBefore.y + composerBefore.height < 780);
  const frameBefore = await page.locator('iframe[data-eac-frame="recommendations"]').boundingBox();
  assert.ok(frameBefore.height <= 760);
  const currentInput = await page.getByRole('textbox', { name: '测试草稿' }).boundingBox();
  assert.equal(currentInput.height, originalInput.height);
  assert.equal(composerBefore.height, originalComposer.height);
  assert.equal(composerBefore.y, originalComposer.y);
  assert.equal(composerBefore.width, originalComposer.width);
  assert.equal(await picker.locator('.brand-mark img').getAttribute('src'), '/eac-avatar.jpg');
  assert.ok(await picker.locator('.brand-mark img').evaluate(image => image.complete && image.naturalWidth > 0));
