  await page.getByRole('menuitem', { name: '剪辑模式', exact: true }).click();
  await page.locator('[data-eac-intro-seat]:not([hidden]) .eac-intro').waitFor();
  assert.equal(await page.getByRole('textbox', { name: '测试草稿' }).inputValue(), '你好');
  await picker.getByRole('button', { name: '选择逐帧手绘', exact: true }).click();
  await page.locator('.eac-selection-chip[data-eac-selection-id="05-cel-boil"]').waitFor();
  assert.equal(await page.getByRole('textbox', { name: '测试草稿' }).inputValue(), '你好');
  await picker.getByRole('button', { name: '取消选择逐帧手绘', exact: true }).waitFor();
  await picker.getByRole('button', { name: '取消选择逐帧手绘', exact: true }).click();
  await page.locator('.eac-selection-chip').waitFor({ state: 'detached' });
  await picker.getByRole('button', { name: '选择逐帧手绘', exact: true }).click();
  await page.locator('.eac-selection-chip').waitFor();
  await page.getByRole('button', { name: '取消选择逐帧手绘', exact: true }).click();
  await page.locator('.eac-selection-chip').waitFor({ state: 'detached' });
  await page.waitForFunction(async origin => {
    const response = await fetch(`${origin}/api/composer?sessionId=qa-composer-session`);
    return !(await response.json()).templateId;
  }, app.url);
  assert.equal(await page.getByRole('textbox', { name: '测试草稿' }).inputValue(), '你好');
  checks.push('Template chip renders without raw draft markers; card toggle and chip removal clear session selection');
  await page.locator('[data-eac-intro-seat]:not([hidden]) .eac-intro').waitFor();
  checks.push('Typed draft and selected template survive edit → normal → edit without hiding recommendations');
  await page.getByRole('button', { name: '创作模式: 剪辑模式', exact: true }).click();
  await page.getByRole('menuitem', { name: 'Design 模式', exact: true }).click();
  await page.locator('[data-eac-intro-seat]:not([hidden]) .eac-intro').waitFor();
  assert.match(await page.getByRole('textbox', { name: '测试草稿' }).inputValue(), /^你好/);
  checks.push('Design recommendations remain visible with a nonempty draft');
  await page.getByRole('button', { name: '作品预览画布', exact: true }).click();
  await page.locator('iframe[data-eac-frame="canvas"]').waitFor();
  checks.push('Design mode and native-sidebar body registration open the real canvas iframe');
  await page.screenshot({ path: join(directory, 'composer-native-canvas.png') });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto(`${fixtureUrl}/tests/fixtures/composer.html?backend=${encodeURIComponent(app.url)}&wideLayout=1`, { waitUntil: 'domcontentloaded' });
  const wideOriginal = await page.locator('[data-composer-card]').boundingBox();
  await page.getByRole('button', { name: '创作模式: Design 模式', exact: true }).click();
  await page.getByRole('menuitem', { name: '剪辑模式', exact: true }).click();
  await page.locator('[data-eac-intro-seat]:not([hidden]) .eac-intro').waitFor();
  const wideCard = await page.locator('[data-composer-card]').boundingBox();
  const gallery = page.locator('[data-eac-intro-seat] .eac-intro');
  await page.waitForFunction(() => {
    const card = document.querySelector('[data-composer-card]')?.getBoundingClientRect();
    const gallery = document.querySelector('.eac-intro')?.getBoundingClientRect();
    return card && gallery && gallery.width > card.width + 100;
  });
  const galleryBounds = await gallery.boundingBox();
