import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import { resolve, join } from 'node:path';
import { chromium } from 'playwright';
import { startServer } from '../src/server.mjs';
const directory = resolve('artifacts/picker-redesign');
await mkdir(directory, { recursive: true });
const server = await startServer({ port: 0 });
const browser = await chromium.launch({ channel: 'msedge', headless: true });
const errors = [];
const checks = [];
try {
  const page = await browser.newPage({ viewport: { width: 1050, height: 900 } });
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(`${server.url}/?view=templates&mode=design&kind=website&layout=inline`);
  await page.locator('.library-card').nth(7).waitFor();
  assert.equal(await page.locator('.library-card').count(), 8);
  assert.deepEqual(await page.locator('.library-card').evaluateAll(nodes => [...new Set(nodes.map(node => node.dataset.templateKind))]), ['website']);
  const rows = await page.locator('.library-card').evaluateAll(nodes => new Set(nodes.map(node => node.offsetTop)).size);
  assert.equal(rows, 2);
  assert.ok(await page.locator('.inline-bounded').evaluate(node => node.getBoundingClientRect().height <= 760));
  const cover = await page.locator('.library-card-cover').first().boundingBox();
  assert.ok(Math.abs(cover.width / cover.height - 16 / 9) < 0.03);
  assert.ok(cover.height > 120);
  assert.ok(await page.locator('.library-picker-scroll').evaluate(node => node.scrollHeight <= node.clientHeight + 1));
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.locator('.library-card').first().hover();
  await page.waitForTimeout(250);
  assert.notEqual(await page.locator('.library-card').first().evaluate(node => getComputedStyle(node).transform), 'none');
  await page.screenshot({ path: join(directory, 'website-inline.png'), fullPage: true });
  checks.push('Desktop inline recommendations: eight website cards in exactly two rows, no internal scrolling');
  assert.equal(await page.getByRole('button', { name: /展开更多灵感/ }).count(), 0);
  await page.setViewportSize({ width: 560, height: 800 });
  await page.waitForFunction(() => document.querySelectorAll('.library-card').length === 4);
  assert.equal(await page.locator('.library-card').evaluateAll(nodes => new Set(nodes.map(node => node.offsetTop)).size), 2);
  checks.push('Narrow inline recommendations: four cards in exactly two rows');
  await page.setViewportSize({ width: 1050, height: 900 });
  await page.goto(`${server.url}/?view=templates&mode=design&kind=website`);
  await page.locator('.library-card').nth(23).waitFor();
  const website = await page.locator('.library-card h3').allTextContents();
  await page.getByRole('tab', { name: '幻灯片', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('.library-picker')?.dataset.kind === 'deck');
  assert.notDeepEqual(await page.locator('.library-card h3').allTextContents(), website);
  assert.deepEqual(await page.locator('.library-card').evaluateAll(nodes => [...new Set(nodes.map(node => node.dataset.templateKind))]), ['deck']);
  checks.push('Creation tab switches actual dataset, not only highlight');
  await page.getByRole('tab', { name: /设计体系/ }).click();
  await page.locator('.library-picker[data-section="systems"]').waitFor();
  assert.equal(await page.locator('.library-card').count(), 24);
  const scroll = await page.locator('.library-picker-scroll').evaluate(node => { node.scrollTop = node.scrollHeight; return { top: node.scrollTop, height: node.clientHeight, scroll: node.scrollHeight }; });
  assert.ok(scroll.top > 0);
  await page.getByRole('button', { name: '下一页模板', exact: true }).click();
  await page.getByText('每页 24 项 · 第 2 / 7 页', { exact: true }).waitFor();
  await page.screenshot({ path: join(directory, 'systems-paged.png') });
  checks.push('System library scrolls fully and paginates 152 systems in seven pages');
  assert.deepEqual(errors, []);
  await writeFile(join(directory, 'results.json'), JSON.stringify({ checks, errors }, null, 2));
  console.log(JSON.stringify({ checks, errors }, null, 2));
} finally { await browser.close(); await server.close(); }
